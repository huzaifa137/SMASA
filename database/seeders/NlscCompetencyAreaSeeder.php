/**
 * php artisan db:seed --class=NlscCompetencyAreaSeeder
 *
 * Seeds the platform-wide NCDC "Activities of Integration" (Competency
 * Area) catalogue (Senior 1-4) into the admin side, the same starter set
 * every school automatically pulls in the first time it visits either
 * the "Activities of Integration" or "Subject Achievement" screen for a
 * given Senior/Subject (SchoolNlscTopicController::
 * cloneFromAdminIfNeeded()). Nothing needs to be pushed to schools
 * manually here — an already synced school still gets each new
 * statement immediately too, since this calls the same
 * NlscSyncService::propagateNewTopicCompetencyArea() the admin "Add"
 * button itself uses.
 *
 * Topics are shared with Subject Achievement (one nlsc_topics
 * catalogue — see NlscSubjectAchievementController's docblock) — a
 * topic already created by that feature (or a previous run of this one)
 * is reused rather than duplicated; a topic that doesn't exist yet is
 * created here first, exactly the way NlscTopicController::store()
 * creates one (same fields, same next-available sort_order).
 *
 * Senior/Subject names are matched case-insensitively against the
 * SECONDARY_OLEVEL_CLASSES / NLSC_SUBJECTS master-data groups, the same
 * lookup NlscTopicBulkImport uses — with a short list of aliases for
 * names the catalogue spells differently than master-data commonly does
 * (e.g. "English Language" vs "English"). The source material splits
 * Senior 2 Religious Education into "Christian Religious Education" and
 * "Islamic Religious Education" specifically (CRE/IRE each have their
 * own NCDC syllabus), so those are seeded as two distinct subjects
 * rather than folded into one generic "Religious Education" — resolve
 * those against whichever CRE/IRE master-data entries your install
 * actually has (or add the aliases below to match your naming). Any
 * Senior/Subject that still can't be resolved is skipped with a warning
 * rather than failing the whole run, since master-data naming can vary
 * between installs.
 *
 * Safe to re-run: an existing topic is reused (never duplicated), and a
 * competency area already present with the exact same wording is left
 * alone rather than added again — only genuinely new statements (e.g.
 * after the catalogue below is extended) get created and pushed out on
 * a second run.
 */
class NlscCompetencyAreaSeeder extends Seeder
{
    /**
     * Extra name(s) to also try, in order, when the catalogue's subject
     * name doesn't match any master-data NLSC_SUBJECTS row exactly.
     * Keyed by the catalogue's own uppercase subject name.
     */
    private const SUBJECT_ALIASES = [
        'ENGLISH LANGUAGE' => ['ENGLISH'],
        'HISTORY AND POLITICAL EDUCATION' => ['HISTORY', 'HISTORY & POLITICAL EDUCATION'],
        'PHYSICAL EDUCATION' => ['PE'],
        'CHRISTIAN RELIGIOUS EDUCATION' => ['CRE'],
        'ISLAMIC RELIGIOUS EDUCATION' => ['IRE'],
    ];

    /**
     * CRE and IRE share identical topic names ("Respect for Human
     * Life", "Marriage", "Family") in this catalogue, so falling both
     * back to one generic "Religious Education" subject would merge two
     * different syllabuses' competency areas onto the same topic with
     * no way to tell which came from which. So, unlike every other
     * subject, these two are matched by exact name (plus the CRE/IRE
     * alias above) only — never by the loose contains-match in
     * resolveSubjectId() — and are skipped with a warning rather than
     * risk that merge if your master data doesn't have them split out.
     */
    private const NO_LOOSE_MATCH = ['CHRISTIAN RELIGIOUS EDUCATION', 'ISLAMIC RELIGIOUS EDUCATION'];

    public function run(): void
    {
        $seniorLookup = Helper::MasterRecords(config('constants.options.SECONDARY_OLEVEL_CLASSES'))
            ->mapWithKeys(fn($m) => [strtolower(trim($m->md_name)) => $m->md_id]);

        $subjectLookup = Helper::MasterRecords(config('constants.options.NLSC_SUBJECTS'))
            ->mapWithKeys(fn($m) => [strtolower(trim($m->md_name)) => $m->md_id]);

        $topicsCreated = 0;
        $topicsReused = 0;
        $areasCreated = 0;
        $areasSkipped = 0;
        $subjectsSkipped = [];

        foreach ($this->catalogue() as $block) {
            $seniorId = $seniorLookup[strtolower("senior {$block['senior']}")] ?? null;

            $subjectId = $this->resolveSubjectId($block['subject'], $subjectLookup);

            if (!$seniorId || !$subjectId) {
                $subjectsSkipped[] = "Senior {$block['senior']} — {$block['subject']}";
                continue;
            }

            foreach ($block['topics'] as $row) {
                $topic = NlscTopic::where('senior_class_id', $seniorId)
                    ->where('subject_id', $subjectId)
                    ->where('topic_name', $row['topic'])
                    ->first();

                if ($topic) {
                    $topicsReused++;
                } else {
                    $nextOrder = 1 + (int) NlscTopic::where('senior_class_id', $seniorId)
                        ->where('subject_id', $subjectId)
                        ->max('sort_order');

                    $topic = NlscTopic::create([
                        'senior_class_id' => $seniorId,
                        'subject_id' => $subjectId,
                        'topic_name' => $row['topic'],
                        'sort_order' => $nextOrder,
                    ]);
                    $topicsCreated++;
                }

                foreach ($row['areas'] as $description) {
                    $alreadyHasIt = NlscCompetencyArea::where('nlsc_topic_id', $topic->id)
                        ->where('description', $description)
                        ->exists();

                    if ($alreadyHasIt) {
                        $areasSkipped++;
                        continue;
                    }

                    $nextAreaOrder = 1 + (int) NlscCompetencyArea::where('nlsc_topic_id', $topic->id)
                        ->max('sort_order');

                    $area = NlscCompetencyArea::create([
                        'nlsc_topic_id' => $topic->id,
                        'description' => $description,
                        'sort_order' => $nextAreaOrder,
                    ]);

                    NlscSyncService::propagateNewTopicCompetencyArea($topic, $area);
                    $areasCreated++;
                }
            }
        }

        if ($this->command) {
            $this->command->info("Topics created: {$topicsCreated}, reused: {$topicsReused}");
            $this->command->info("Competency areas created: {$areasCreated}, already present: {$areasSkipped}");
            if ($subjectsSkipped) {
                $this->command->warn('Skipped (Senior/Subject not found in master data): ' . implode('; ', $subjectsSkipped));
                $this->command->warn('Add these to SECONDARY_OLEVEL_CLASSES / NLSC_SUBJECTS master data (or to SUBJECT_ALIASES above) and re-run — already-seeded rows are left untouched.');
            }
        }
    }

    /**
     * Tries the catalogue's own subject name first, then each alias in
     * SUBJECT_ALIASES, then finally a loose "one name contains the
     * other" match against every NLSC_SUBJECTS row — catches spacing/
     * wording differences without needing every variant listed
     * explicitly above.
     */
    private function resolveSubjectId(string $subjectName, $subjectLookup): ?int
    {
        $key = strtolower(trim($subjectName));
        if (isset($subjectLookup[$key])) {
            return $subjectLookup[$key];
        }

        foreach (self::SUBJECT_ALIASES[$subjectName] ?? [] as $alias) {
            $aliasKey = strtolower(trim($alias));
            if (isset($subjectLookup[$aliasKey])) {
                return $subjectLookup[$aliasKey];
            }
        }

        $normalized = fn($s) => preg_replace('/[^a-z0-9]/', '', strtolower($s));

        if (in_array($subjectName, self::NO_LOOSE_MATCH, true)) {
            return null;
        }

        $needle = $normalized($subjectName);
        foreach ($subjectLookup as $name => $id) {
            $hay = $normalized($name);
            if ($hay !== '' && (str_contains($needle, $hay) || str_contains($hay, $needle))) {
                return $id;
            }
        }

        return null;
    }

